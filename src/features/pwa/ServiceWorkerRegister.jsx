// ثبتِ سرویس‌ورکر در همان لحظه‌ی اولِ خوانده‌شدنِ صفحه.
//
// 🔴 باگی که اینجا رفع شد — «دکمه‌ی نصب فقط چند ثانیه بعد آماده می‌شود»:
//
// کروم تا وقتی یک سرویس‌ورکرِ **فعال** نبیند، سایت را «قابلِ نصب» نمی‌شناسد و اجازه‌ی نصب
// (رویدادِ beforeinstallprompt) را اعلام نمی‌کند. پس هرچه ثبتِ سرویس‌ورکر دیرتر شروع شود،
// دکمه‌ی نصب هم دیرتر آماده می‌شود.
//
// نسخه‌ی قبلی این کار را داخلِ useEffect و **بعد از رویدادِ `load`** انجام می‌داد؛ یعنی ثبت
// وقتی شروع می‌شد که همه‌ی عکس‌ها و فونت‌ها دانلود شده و جاوااسکریپتِ React هم بالا آمده
// باشد. روی صفحه‌ی اصلی — با عکسِ بزرگِ هیرو و دو کوئریِ دیتابیس — این چند ثانیه بعد از
// بازشدنِ صفحه است. زنجیره‌ی بعدی هم خودش زمان می‌برد (ثبت → نصب → فعال‌سازی → گرفتنِ
// کنترلِ صفحه → بازبینیِ قابلِ نصب بودن → اعلامِ اجازه).
//
// نتیجه‌اش دقیقاً همان چیزی بود که دیده می‌شد: کاربری که همان اول دکمه‌ی نصب را می‌زد پیامِ
// «هنوز آماده نیست» می‌گرفت، ولی اگر به صفحه‌ی دیگری می‌رفت و برمی‌گشت (که چند ثانیه طول
// می‌کشد) دکمه‌ی واقعیِ نصب را می‌دید.
//
// راهِ حل: همان الگوی InstallCapture — یک اسکریپتِ کوچکِ خام که هنگامِ **خواندنِ HTML**
// اجرا می‌شود، پیش از دانلودِ عکس‌ها و پیش از بالا آمدنِ React.
//
// 🌍 آنالوژی: کلیدِ برق را همان لحظه‌ی ورود به اتاق بزن، نه بعد از اینکه همه‌ی وسایل را
// چیدی — روشن‌شدنِ لامپ خودش چند لحظه طول می‌کشد.
//
// ⚠️ این اسکریپت باید «چندبار-اجرا-امن» باشد: محتوایش دو بار در صفحه می‌آید (یک‌بار به‌عنوانِ
// اسکریپتِ واقعی و یک‌بار داخلِ داده‌ای که React برای بالا آوردنِ صفحه می‌فرستد)، و ثبتِ
// دوباره‌ی سرویس‌ورکر کارِ بی‌خودی است. پس با یک نگهبان فقط یک‌بار اجرا می‌شود.
const REGISTER_SCRIPT = `(function(){
  if (window.__swBooted) return;
  window.__swBooted = true;
  if (!('serviceWorker' in navigator)) return;
  navigator.serviceWorker.register('/sw.js').catch(function (err) {
    // خطای ثبت نباید اپ را بشکند؛ فقط لاگ می‌کنیم.
    console.error('SW registration failed:', err);
  });
})();`;

// چیزی روی صفحه نمی‌کشد؛ فقط اسکریپتِ بالا را در خروجیِ صفحه می‌گذارد.
//
// در محیطِ توسعه هیچ اسکریپتی تولید نمی‌شود تا سرویس‌ورکر با HMR (تازه‌سازیِ خودکارِ کد
// هنگامِ نوشتن) تداخل نکند. چون این یک کامپوننتِ سرور است، این شرط همان لحظه‌ی ساختنِ
// صفحه سنجیده می‌شود — نه در مرورگرِ کاربر.
export default function ServiceWorkerRegister() {
  if (process.env.NODE_ENV !== 'production') return null;
  return <script dangerouslySetInnerHTML={{ __html: REGISTER_SCRIPT }} />;
}
