'use client';

// تشخیصِ «این کاربر روی چه چیزی است و چطور می‌تواند اپ را نصب کند».
//
// 🔴 واقعیتی که این فایل رویش بنا شده:
// نمایشِ پنجره‌ی نصبِ خودِ مرورگر **فقط** وقتی ممکن است که مرورگر اجازه‌اش را اعلام کرده
// باشد. هیچ API‌ای وجود ندارد که بشود آن پنجره را به‌زور باز کرد. و روی آیفون/آی‌پد اصلاً
// چنین قابلیتی در هیچ شکلی وجود ندارد — تنها راه، مسیرِ دستیِ اپل است.
//
// پس وقتی نصبِ یک‌کلیکی ممکن نیست، بهترین کارِ ممکن این است که **دقیقاً همان مسیرِ دستیِ
// همان دستگاه** را قدم‌به‌قدم نشان بدهیم، نه یک پیامِ کلی.

// آیفون و آی‌پد.
// ⚠️ آی‌پدهای جدید خودشان را «Macintosh» معرفی می‌کنند، برای همین لمسی‌بودن هم چک می‌شود.
export function isAppleMobile() {
  if (typeof window === 'undefined') return false;
  const ua = window.navigator.userAgent;
  if (/iphone|ipad|ipod/i.test(ua)) return true;
  return /Macintosh/.test(ua) && window.navigator.maxTouchPoints > 1;
}

function isAndroid() {
  if (typeof window === 'undefined') return false;
  return /android/i.test(window.navigator.userAgent);
}

function isFirefox() {
  if (typeof window === 'undefined') return false;
  return /firefox|fxios/i.test(window.navigator.userAgent);
}

/**
 * راهنمای نصب متناسب با دستگاه و مرورگرِ همین کاربر.
 *
 * فیلدِ `canPromptEventually` یعنی «این مرورگر نصبِ یک‌کلیکی را **بلد است**، فقط هنوز
 * اجازه‌اش را نداده». تفاوتش با آیفون و فایرفاکس حیاتی است:
 *   • آیفون / فایرفاکس ⇒ هرگز دکمه‌ای نخواهد آمد؛ مسیرِ دستی تنها راه است.
 *   • کروم / اِج       ⇒ دکمه **می‌آید**، فقط باید چند لحظه صبر کرد.
 * بدونِ این تفکیک، به کاربرِ کروم می‌گفتیم «برو از منو نصب کن» در حالی که چند ثانیه بعد
 * دکمه‌ی یک‌کلیکی برایش فعال می‌شد — و او نتیجه می‌گرفت اپ خراب است.
 *
 * @returns {{ title: string, intro: string, steps: string[], note?: string, canPromptEventually: boolean }}
 */
export function getInstallGuide() {
  if (isAppleMobile()) {
    return {
      canPromptEventually: false,
      title: 'نصب روی آیفون / آی‌پد',
      intro:
        'روی دستگاه‌های اپل، نصب فقط به‌صورت دستی انجام می‌شود. این محدودیتِ خودِ اپل است و هیچ سایتی نمی‌تواند آن را دور بزند — ولی فقط سه قدم است:',
      steps: [
        'در نوارِ پایینِ سافاری، دکمه‌ی «اشتراک‌گذاری» را بزن (مربعی که یک فلش رو به بالا دارد).',
        'کمی پایین برو و گزینه‌ی «Add to Home Screen» یا «افزودن به صفحه اصلی» را انتخاب کن.',
        'بالا سمت راست «Add» را بزن. آیکنِ اپ روی صفحه‌ی اصلیِ گوشی‌ات می‌نشیند.',
      ],
      note: 'اگر گزینه‌ی «Add to Home Screen» را نمی‌بینی، یعنی صفحه را در مرورگری جز سافاری باز کرده‌ای. لینک را در سافاری باز کن.',
    };
  }

  if (isFirefox()) {
    return {
      canPromptEventually: false,
      title: 'نصب روی فایرفاکس',
      intro: 'فایرفاکس نصبِ یک‌کلیکی را پشتیبانی نمی‌کند. دو راه داری:',
      steps: [
        'ساده‌ترین راه: همین آدرس را در «کروم» یا «اِج» باز کن و دوباره دکمه‌ی نصب را بزن.',
        'یا در فایرفاکسِ اندروید، از منوی سه‌نقطه گزینه‌ی «Install» / «افزودن به صفحه اصلی» را بزن.',
      ],
    };
  }

  if (isAndroid()) {
    return {
      canPromptEventually: true,
      title: 'نصب روی اندروید',
      intro: 'این مسیرِ دستی همیشه و همین حالا کار می‌کند:',
      steps: [
        'از منوی سه‌نقطه‌ی بالای مرورگر، گزینه‌ی «Install app» یا «نصب برنامه» را بزن.',
        'اگر به‌جایش «Open in app» دیدی، یعنی اپ از قبل نصب شده — همان آیکن را روی صفحه‌ی گوشی‌ات باز کن.',
      ],
      note: 'اگر هیچ‌کدام از این دو گزینه در منو نبود، صفحه را یک‌بار رفرش کن و چند ثانیه صبر کن، بعد دوباره امتحان کن.',
    };
  }

  // کروم/اِجِ دسکتاپ و بقیه.
  return {
    canPromptEventually: true,
    title: 'نصب روی کامپیوتر',
    intro: 'این مسیرِ دستی همیشه و همین حالا کار می‌کند:',
    steps: [
      'سمتِ راستِ نوارِ آدرس دنبالِ آیکنِ کوچکِ نصب بگرد (یک صفحه‌نمایش با فلشِ رو به پایین) و بزنش.',
      'اگر آن آیکن نبود، از منوی سه‌نقطه‌ی مرورگر گزینه‌ی «Install banad barber» یا «Cast, save and share ← Install page as app» را بزن.',
    ],
    note: 'اگر در منو گزینه‌ی «Open in banad barber» دیدی، یعنی اپ از قبل روی همین کامپیوتر نصب شده است.',
  };
}
