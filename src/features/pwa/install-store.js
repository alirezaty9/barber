'use client';

import { create } from 'zustand';

// وضعیتِ مشترکِ نصبِ اپ — یک منبعِ حقیقت برای هر دو دکمه‌ی نصب.
//
// 🔴 چرا لازم است؟ در صفحه‌ی اصلی دو راهِ نصب وجود دارد: آیکنِ گوشی در ردیفِ آیکن‌های
// بالای صفحه، و کادرِ «نصب اپلیکیشن» در پایینِ صفحه. اجازه‌ی نصبی که مرورگر می‌دهد
// **یک‌بارمصرف** است. اگر هرکدام وضعیتِ خودش را جدا نگه دارد، به‌محضِ اینکه یکی مصرفش
// کند آن یکی هنوز فکر می‌کند اجازه دستش است — و کلیکِ بعدی روی آن بی‌صدا شکست می‌خورد.
//
// با این وضعیتِ مشترک، هر دو همیشه یک چیز می‌دانند.
export const usePwaInstallStore = create((set) => ({
  // آیا همین حالا نصبِ یک‌کلیکی ممکن است؟
  canInstall: false,
  // آیا اپ به‌شکلِ نصب‌شده باز شده (یا همین الان نصب شد)؟
  installed: false,

  setCanInstall: (canInstall) => set({ canInstall }),
  markInstalled: () => set({ installed: true, canInstall: false }),
}));
