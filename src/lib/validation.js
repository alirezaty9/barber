import { z } from 'zod';
import { normalizeDigits } from './persian';
import { tehranTodayISO, shiftISO } from './time';
import { TIME_SLOTS } from './constants';

// حداکثر فاصله‌ی مجازِ رزرو از امروز (روز): فقط تا «یک هفته‌ی» آینده.
// این با تعدادِ روزهای نمایش‌داده‌شده در DayPicker (۸ روز = امروز + ۷) هماهنگ است.
export const MAX_BOOKING_ADVANCE_DAYS = 7;

// آیا رشته‌ی YYYY-MM-DD یک تاریخِ واقعیِ تقویمی است؟ (regex تنها «2026-13-45» را رد نمی‌کند.)
function isRealISODate(v) {
  const [y, m, d] = v.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === m - 1 && dt.getUTCDate() === d;
}

export const CATEGORIES = ['hair', 'beard', 'grooming', 'groom', 'combo', 'style'];
export const STATUSES = ['pending', 'confirmed', 'cancelled'];

// شماره‌ی موبایل: ابتدا ارقام فارسی/عربی به انگلیسی نرمال می‌شود، سپس اعتبارسنجی.
// قالبِ معتبر: ۱۱ رقمی که با ۰۹ شروع شود.
const mobile = z
  .string()
  .transform((v) => normalizeDigits(v).trim())
  .refine((v) => /^09[0-9]{9}$/.test(v), {
    message: 'شماره موبایل باید ۱۱ رقمی و با ۰۹ شروع شود.',
  });

// کدِ تأییدِ ۶ رقمی (OTP) — ارقام فارسی/عربی هم پذیرفته و نرمال می‌شوند.
const otp = z
  .string()
  .transform((v) => normalizeDigits(v).trim())
  .refine((v) => /^[0-9]{6}$/.test(v), { message: 'کد تأیید باید ۶ رقمی باشد.' });

// تاریخِ ISO: هم قالب (regex) و هم صحتِ تقویمی چک می‌شود.
const isoDate = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/, { message: 'تاریخ نامعتبر است.' })
  .refine(isRealISODate, { message: 'تاریخ نامعتبر است.' });

// تاریخِ رزرو: علاوه بر معتبربودن، نباید در گذشته یا دورتر از سقفِ مجاز باشد.
//
// 🔴 کفِ بازه دقیقاً «امروزِ تهران» است، نه «دیروز». قبلاً یک روز ارفاق داشت (احتمالاً برای
// پوششِ اختلافِ تایم‌زونِ مرورگر) ولی آن ارفاق یک درِ باز می‌ساخت: چکِ «ساعتِ گذشته» فقط
// وقتی فعال می‌شود که روزِ انتخابی همان امروز باشد، پس برای دیروز همه‌ی ساعت‌ها «آزاد»
// دیده می‌شدند و رزروِ گذشته قابلِ ساختن بود. ارفاق لازم هم نیست: کلاینت و سرور هر دو
// «امروز» را از tehranTodayISO می‌گیرند، پس اختلافی وجود ندارد.
const bookingDate = isoDate
  .refine((v) => v >= tehranTodayISO(), { message: 'تاریخِ گذشته قابلِ رزرو نیست.' })
  .refine((v) => v <= shiftISO(tehranTodayISO(), MAX_BOOKING_ADVANCE_DAYS), {
    message: 'این تاریخ خیلی دور است.',
  });

// ساعت باید یکی از اسلات‌های واقعیِ آرایشگاه باشد، نه هر «HH:MM»ی. اگر فقط قالب چک شود،
// ساعتی مثلِ 13:00 (که جزوِ اسلات‌ها نیست) پذیرفته می‌شود و بعد در هیچ محاسبه‌ای دیده
// نمی‌شود: بستنِ ساعت بی‌اثر می‌مانَد و رزرو در برنامه‌ی روزانه نامرئی می‌شود.
const timeSlot = z
  .string()
  .regex(/^\d{2}:\d{2}$/, { message: 'ساعت نامعتبر است.' })
  .refine((v) => TIME_SLOTS.includes(v), { message: 'این ساعت جزوِ ساعاتِ کاری نیست.' });

// تصویرِ خدمت: خالی، یا آدرسِ http(s)/مسیرِ لوکال، یا data URLِ عکس (آپلودِ ادمین).
// سقفِ حجم گذاشته می‌شود تا یک data URLِ خیلی بزرگ دیتابیس/پاسخ را سنگین نکند.
const serviceImage = z
  .string()
  .trim()
  .default('')
  .refine(
    (v) =>
      v === '' ||
      /^https?:\/\//.test(v) ||
      v.startsWith('/') ||
      /^data:image\/(png|jpe?g|webp);base64,/.test(v),
    { message: 'تصویر نامعتبر است.' },
  )
  .refine((v) => v.length <= 900_000, {
    message: 'حجم تصویر زیاد است؛ عکسِ کوچک‌تری انتخاب کن.',
  });

export const serviceSchema = z.object({
  name: z.string().trim().min(1, 'عنوان خدمت الزامی است.').max(80, 'عنوان خدمت خیلی طولانی است.'),
  price: z.coerce.number().int().positive('قیمت باید بزرگ‌تر از صفر باشد.'),
  // «مدت خدمت» از رابط کاربری حذف شده (هر نوبت ۱ ساعت و ربع ثابت است). ولی ستونِ
  // duration در دیتابیس اجباری است؛ پس اگر فرستاده نشد، پیش‌فرضِ ۷۵ دقیقه می‌گیرد.
  duration: z.coerce.number().int().positive().default(75),
  description: z.string().trim().max(500, 'توضیح خیلی طولانی است.').default(''),
  category: z.enum(CATEGORIES),
  image: serviceImage,
});

// 🧹 پاک‌سازیِ ۱۴۰۵/۰۶/۲۸ — پروژه تک‌آرایشگره است.
// فیلدهای «تخصص»، «آواتار»، «عکسِ بزرگ»، «امتیاز» و «بیوگرافی» از این اسکیما حذف شدند:
// بازمانده‌ی نسخه‌ی چندآرایشگره بودند و هیچ صفحه‌ای در سایت نمایششان نمی‌داد.
// ⚠️ ستون‌هایشان در دیتابیس دست‌نخورده ماند (همه مقدارِ پیش‌فرض دارند). حذفِ ستون یعنی یک
// عملیاتِ دستی روی دیتابیسِ زنده که سودی ندارد و فقط ریسکِ ازدست‌رفتنِ داده می‌آورد.
export const barberSchema = z.object({
  name: z.string().trim().min(1, 'نام آرایشگر الزامی است.').max(60, 'نام خیلی طولانی است.'),
  // 🔴 حداقل یک روزِ کاری اجباری است. آرایه‌ی خالی به رشته‌ی خالی ذخیره می‌شد و سمتِ خواندن
  // رشته‌ی خالی به معنای «پیکربندی‌نشده ⇒ همه‌ی روزها کاری» تفسیر می‌شود؛ یعنی «هیچ روزی
  // کاری نیست» دقیقاً برعکس می‌شد و آرایشگر هر روز قابلِ رزرو می‌شد.
  workDays: z
    .array(z.coerce.number().int().min(0).max(6))
    .min(1, 'حداقل یک روزِ کاری انتخاب کنید.')
    .default([0, 1, 2, 3, 4, 5, 6]),
});

export const bookingSchema = z.object({
  customerName: z.string().trim().min(1, 'نام و نام خانوادگی الزامی است.').max(60, 'نام خیلی طولانی است.'),
  customerPhone: mobile,
  // یک یا چند خدمت. دو قید مهم:
  //  • سقفِ تعداد (۱۰): جلوی درخواستِ سوءاستفاده‌گر با هزاران شناسه را می‌گیرد که هم کوئریِ
  //    دیتابیس را سنگین می‌کرد و هم مبلغ را بی‌مرز بالا می‌برد. رابطِ کاربری هرگز به آن نمی‌رسد.
  //  • بی‌تکرار: قبلاً [A, A] پذیرفته می‌شد و مبلغ دو برابرِ قیمتِ همان یک خدمت محاسبه و به
  //    درگاه فرستاده می‌شد (چکِ اعتبار با شمارشِ طول انجام می‌شد و تکراری را نمی‌دید).
  serviceIds: z
    .array(z.string().min(1))
    .min(1, 'حداقل یک خدمت انتخاب کنید.')
    .max(10, 'تعداد خدمات انتخابی بیش از حد مجاز است.')
    .refine((ids) => new Set(ids).size === ids.length, {
      message: 'یک خدمت نمی‌تواند دو بار انتخاب شود.',
    }),
  // آرایشگر اختیاری؛ چون تک‌آرایشگری است، اگر ارسال نشود سمت سرور همان آرایشگر انتخاب می‌شود.
  barberId: z.string().min(1).nullish(),
  date: bookingDate,
  timeSlot,
});

// پارامترهای آدرسِ «ساعت‌های آزاد» (مسیرِ عمومی). قبلاً هیچ اعتبارسنجی‌ای نداشت: تاریخِ
// بی‌معنا پاسخِ ۲۰۰ با «روزِ تعطیل» می‌داد (گمراه‌کننده)، و تاریخِ دور موجودیِ فراتر از سقفِ
// مجازِ رزرو را افشا می‌کرد. با bookingDate همان قیدِ «امروز تا یک هفته» اعمال می‌شود.
export const availabilityQuerySchema = z.object({
  barberId: z.string().min(1, 'آرایشگر نامعتبر است.'),
  date: bookingDate,
});

// رزروِ دستیِ ادمین: همان فیلدهای رزرو + اینکه وجهش نقدی/حضوری دریافت شده یا نه.
// قبلاً همیشه «پرداخت‌شده» ثبت می‌شد و بی‌درنگ وارد درآمدِ داشبورد می‌شد، حتی برای مشتریِ
// تلفنی که هنوز پولی نداده بود — یعنی عددِ درآمد جلوتر از واقعیت می‌رفت.
export const manualBookingSchema = bookingSchema.extend({
  paid: z.boolean().default(true),
});

// تغییرِ وضعیتِ نوبت توسط ادمین: یا وضعیتِ نوبت، یا وضعیتِ پرداخت (یا هر دو).
//
// 🔴 چرا paymentStatus اضافه شد؟ وضعیتِ «در انتظار استرداد» (refundPending) وقتی ساخته
// می‌شود که پول گرفته شده ولی نوبت قطعی نشده. تا پیش از این هیچ مسیری این ستون را نمی‌پذیرفت،
// پس آن رکورد یک بن‌بست بود: ادمین حتی بعد از واریزِ دستیِ پول به مشتری هم نمی‌توانست
// علامتش بزند و آن نوبت تا ابد در حالتِ معلق می‌ماند.
// مقادیرِ مجاز عمداً محدود است: «مسترد شد» (تسویه انجام شد) یا «پرداخت‌شده» (پول نزدِ
// آرایشگاه ماند و با مشتری به توافقِ دیگری رسیدند).
// ⚠️ عمداً «یکی از دو تا»، نه «هر دو با هم»: تغییرِ وضعیتِ نوبت و تسویه‌ی مالی دو کارِ
// جدا با دو مجموعه‌ی قاعده‌اند. اگر ترکیبشان مجاز بود، یک درخواستِ دوفیلدی می‌توانست از
// کنارِ گاردهای «نوبتِ لغوشده دوباره تایید نمی‌شود» رد شود.
export const statusUpdateSchema = z
  .object({
    status: z.enum(STATUSES).optional(),
    paymentStatus: z.enum(['paid', 'refunded']).optional(),
  })
  .refine((v) => Boolean(v.status) !== Boolean(v.paymentStatus), {
    message: 'دقیقاً یکی از «وضعیت نوبت» یا «وضعیت پرداخت» را مشخص کنید.',
  });

export const loginSchema = z.object({
  password: z.string().min(1, 'رمز عبور را وارد کنید.'),
});

// رهگیری نوبت فقط با شماره موبایل.
export const lookupSchema = z.object({
  phone: mobile,
});

// درخواستِ کدِ تأییدِ لغو: فقط با کدِ رهگیری؛ سرور OTP را به موبایلِ همان نوبت می‌فرستد.
export const cancelRequestSchema = z.object({
  code: z.string().trim().min(1, 'کد رهگیری نامعتبر است.'),
});

// لغو نوبت: کدِ رهگیری + کدِ تأییدِ دومرحله‌ای.
export const cancelSchema = z.object({
  code: z.string().trim().min(1, 'کد رهگیری نامعتبر است.'),
  otp,
});

// بستن زمان (مرخصی/تعطیلی): کل روز (fullDay=true، از date تا dateTo) یا ساعت‌های مشخص (slots).
export const blockSchema = z
  .object({
    barberId: z.string().min(1, 'انتخاب آرایشگر الزامی است.'),
    date: isoDate,
    dateTo: isoDate.nullish(),
    fullDay: z.boolean().default(false),
    slots: z.array(timeSlot).max(TIME_SLOTS.length, 'تعداد ساعت‌ها بیش از ساعاتِ کاری است.').default([]),
    reason: z.string().trim().max(200, 'متنِ علت خیلی طولانی است.').default(''),
  })
  // 🔴 بازه‌ی معکوس باید خطا بدهد، نه اینکه بی‌صدا به «یک روز» تبدیل شود. قبلاً اگر «تا تاریخ»
  // جلوتر از «از تاریخ» نبود، تابعِ ساختِ بازه فقط همان یک روز را برمی‌گرداند و پیامِ موفقیت
  // داده می‌شد — یعنی آرایشگر فکر می‌کرد چند روز مرخصی گرفته ولی فقط یک روز بسته شده بود.
  .refine((v) => !v.dateTo || v.dateTo >= v.date, {
    message: '«تا تاریخ» نمی‌تواند قبل از «از تاریخ» باشد.',
    path: ['dateTo'],
  });
