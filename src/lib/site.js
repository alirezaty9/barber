// آدرسِ پایه‌ی سایت — تنها منبعِ حقیقت برای ساختِ آدرس‌های مطلق.
//
// چرا لازم است؟ فایل‌های robots و sitemap و متادیتای صفحه باید آدرسِ *کامل* بدهند
// (مثلِ https://example.com/terms، نه /terms). این فایل آن آدرسِ پایه را یک‌جا تعیین
// می‌کند تا اگر دامنه عوض شد، فقط یک متغیرِ محیطی تغییر کند.
//
// 🔴 روی هاستِ لیارا، NEXT_PUBLIC_BASE_URL «اجباری» است، نه اختیاری.
//    برخلافِ بعضی هاست‌ها که دامنه را خودکار در یک متغیرِ محیطی می‌گذارند، لیارا چنین
//    متغیری نمی‌دهد. پس اگر این را ست نکنی، مقدارِ پیش‌فرضِ localhost استفاده می‌شود و
//    فایلِ sitemap و آدرسِ متعارف (canonical) آدرس‌های بی‌معنا به گوگل می‌دهند — بدونِ
//    اینکه سایت ظاهراً خراب به‌نظر برسد. (راهِ تشخیص: آدرسِ /sitemap.xml را باز کن؛
//    اگر داخلش localhost دیدی، یعنی این متغیر ست نشده یا بعدش دوباره دیپلوی نکرده‌ای.)
//
// ⚠️ چون این متغیر با NEXT_PUBLIC_ شروع می‌شود، مقدارش «موقعِ بیلد» داخلِ کد جا می‌افتد.
//    یعنی عوض‌کردنش بدونِ دیپلویِ دوباره هیچ اثری ندارد.
//
// ترتیبِ اولویت:
//   ۱) NEXT_PUBLIC_BASE_URL — مقدارِ صریحی که خودت می‌دهی.
//   ۲) localhost — فقط برای توسعه‌ی محلی.
//
// ⚠️ مسیرِ شروعِ پرداخت (app/api/payment/request) عمداً منطقِ جداگانه‌ی خودش را دارد،
//    چون برخلافِ اینجا به هدرهای خودِ درخواست دسترسی دارد و می‌تواند دقیق‌تر تصمیم بگیرد.
//    به‌محضِ اینکه NEXT_PUBLIC_BASE_URL را ست کنی، هر دو مسیر به یک مقدارِ یکسان می‌رسند.

function resolveSiteUrl() {
  const explicit = process.env.NEXT_PUBLIC_BASE_URL;
  if (explicit) return explicit.replace(/\/$/, '');

  return 'http://localhost:3000';
}

export const SITE_URL = resolveSiteUrl();
