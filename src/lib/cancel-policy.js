// قاعده‌ی «تا کی می‌شود نوبت را لغو کرد» — تنها منبعِ حقیقت.
//
// 🎯 چرا فایلِ جدا؟ این قاعده در دو دنیا لازم است: سرور (که لغو را رد یا قبول می‌کند) و
// مرورگر (که دکمه‌ی لغو را نشان می‌دهد یا نه). اگر هر کدام نسخه‌ی خودش را داشت، دیر یا زود
// از هم جدا می‌افتادند و کاربر دکمه‌ای می‌دید که همیشه خطا می‌داد.
// این فایل عمداً هیچ وابستگیِ سروری ندارد (نه next/server، نه دیتابیس) تا در هر دو جا
// قابلِ import باشد.
import { tehranTodayISO } from './time';

// 🔒 قاعده‌ی کسب‌وکار (تعیینِ صاحبِ مجموعه در ۱۴۰۵/۰۶/۲۸):
// لغو فقط **تا روزِ قبل** ممکن است. از نیمه‌شبِ روزِ نوبت به بعد، مشتری باید تلفنی هماهنگ کند.
//
// چرا مقایسه‌ی «روز» و نه «چند ساعت مانده»؟ چون قاعده خودش روزمحور است: نوبتِ ۹ صبح و
// نوبتِ ۸ شبِ همان روز هر دو یک رفتار دارند. این هم برای مشتری قابلِ فهم‌تر است و هم
// برای آرایشگاه قابلِ برنامه‌ریزی‌تر (صبحِ هر روز، تکلیفِ آن روز روشن است).
export function isWithinCancelWindow(booking) {
  return Boolean(booking?.date) && booking.date > tehranTodayISO();
}

export const CANCEL_TOO_LATE_MESSAGE =
  'لغو نوبت فقط تا روزِ قبل ممکن است. برای امروز لطفاً تلفنی با آرایشگاه هماهنگ کنید.';
