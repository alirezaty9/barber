import { describe, it, expect } from 'vitest';
import { formatJalaliDate, toPersianDigits, normalizeDigits } from '@/lib/persian';
import { weekdayIndexSaturday, shiftISO, rangeISO } from '@/lib/time';

// ─────────────────────────────────────────────────────────────
//  تقویمِ شمسی — نقاطِ مرجعِ قطعی.
//
//  چرا این تست‌ها هستند؟ تبدیلِ میلادی↔شمسی را خودِ موتورِ جاوااسکریپت انجام می‌دهد،
//  پس «درست بودنِ الگوریتم» مسئله نیست. چیزی که می‌تواند بی‌صدا بشکند سه چیز است:
//    ۱) کسی گزینه‌ی timeZone را بردارد ⇒ روی سرورِ UTC تاریخ یک روز عقب می‌افتد
//    ۲) کسی locale را عوض کند ⇒ تقویم میلادی می‌شود بدونِ اینکه خطایی بدهد
//    ۳) قراردادِ «۰=شنبه» با برچسب‌های پنلِ مدیریت واگرا شود ⇒ آرایشگر «شنبه» را
//       می‌بندد و سیستم روزِ دیگری را می‌بندد
// ─────────────────────────────────────────────────────────────

describe('تبدیلِ میلادی به شمسی — نقاطِ مرجع', () => {
  // آغازِ سال‌های شمسی و مرزهای ماه؛ هر کدام یک تاریخِ تقویمیِ قطعی است.
  const CASES = [
    ['2025-03-21', '۱ فروردین'],   // نوروزِ ۱۴۰۴
    ['2026-03-21', '۱ فروردین'],   // نوروزِ ۱۴۰۵
    ['2027-03-21', '۱ فروردین'],   // نوروزِ ۱۴۰۶
    ['2026-03-20', '۲۹ اسفند'],    // آخرین روزِ ۱۴۰۴ (سالِ عادی)
    ['2025-03-20', '۳۰ اسفند'],    // آخرین روزِ ۱۴۰۳ — سالِ کبیسه، ۳۰ اسفند دارد
    ['2026-09-22', '۳۱ شهریور'],   // آخرین روزِ نیمه‌ی اولِ سال (ماه‌های ۱ تا ۶ سی‌ویک‌روزه‌اند)
    ['2026-09-23', '۱ مهر'],       // آغازِ نیمه‌ی دوم
    ['2026-12-21', '۳۰ آذر'],      // ماه‌های ۷ تا ۱۱ سی‌روزه‌اند
  ];

  for (const [iso, expected] of CASES) {
    it(`${iso} → ${expected}`, () => {
      expect(formatJalaliDate(iso)).toBe(expected);
    });
  }

  it('سالِ کبیسه‌ی ۱۴۰۳ واقعاً ۳۰ اسفند دارد و ۱۴۰۴ ندارد', () => {
    expect(formatJalaliDate('2025-03-20')).toBe('۳۰ اسفند');
    // یک روز جلوتر باید نوروز باشد، نه «۳۱ اسفند».
    expect(formatJalaliDate('2025-03-21')).toBe('۱ فروردین');
    // سالِ بعد فقط تا ۲۹ اسفند می‌رود.
    expect(formatJalaliDate('2026-03-20')).toBe('۲۹ اسفند');
  });

  it('ترتیبِ اجزا فارسی است: روزِ هفته، بعد روز، بعد ماه', () => {
    expect(formatJalaliDate('2026-09-20', { weekday: 'long', day: 'numeric', month: 'long' }))
      .toBe('یکشنبه ۲۹ شهریور');
  });

  it('خروجی همیشه ارقامِ فارسی دارد (نه لاتین)', () => {
    expect(formatJalaliDate('2026-09-20')).not.toMatch(/[0-9]/);
  });

  it('ورودیِ نامعتبر باعثِ کرش نمی‌شود و خودِ رشته برمی‌گردد', () => {
    expect(formatJalaliDate('نه-یک-تاریخ')).toBe('نه-یک-تاریخ');
  });

  // 🔴 مهم‌ترین تستِ این فایل: تبدیل نباید به تایم‌زونِ سرور وابسته باشد.
  // سرورِ لیارا معمولاً UTC است و کامپیوترِ توسعه تهران — اگر گزینه‌ی timeZone برداشته
  // شود، همین یک تست می‌شکند و جلوی «تاریخِ یک‌روز-عقب» در پروداکشن را می‌گیرد.
  it('نتیجه به تایم‌زونِ اجرا وابسته نیست', () => {
    const iso = '2026-03-21'; // مرزِ سال — حساس‌ترین نقطه‌ی ممکن
    const direct = new Intl.DateTimeFormat('fa-IR', {
      timeZone: 'UTC', day: 'numeric', month: 'long',
    }).format(new Date(`${iso}T12:00:00Z`));
    expect(formatJalaliDate(iso)).toBe(direct);
    expect(formatJalaliDate(iso)).toBe('۱ فروردین');
  });
});

describe('روزِ هفته — قراردادِ ۰=شنبه', () => {
  // این فهرست باید دقیقاً با WEEK_DAYS در صفحه‌ی «مدیریت آرایشگرها» یکی باشد؛
  // چون آرایشگر همان‌جا تیک می‌زند و availability از همین اندیس استفاده می‌کند.
  const WEEK_DAYS = ['شنبه', 'یکشنبه', 'دوشنبه', 'سه‌شنبه', 'چهارشنبه', 'پنجشنبه', 'جمعه'];

  it('یک هفته‌ی کامل: اندیسِ کد با نامی که مشتری می‌بیند می‌خوانَد', () => {
    // ‎2026-09-19‎ شنبه است.
    let iso = '2026-09-19';
    for (let i = 0; i < 7; i++) {
      const idx = weekdayIndexSaturday(iso);
      expect(idx).toBe(i);
      expect(WEEK_DAYS[idx]).toBe(formatJalaliDate(iso, { weekday: 'long' }));
      iso = shiftISO(iso, 1);
    }
  });

  it('جمعه اندیسِ ۶ است (روزِ تعطیلِ پیش‌فرض)', () => {
    expect(weekdayIndexSaturday('2026-09-25')).toBe(6);
  });
});

describe('جابه‌جاییِ روز روی رشته‌ی ISO', () => {
  it('از مرزِ ماهِ میلادی درست رد می‌شود', () => {
    expect(shiftISO('2026-01-31', 1)).toBe('2026-02-01');
    expect(shiftISO('2026-03-01', -1)).toBe('2026-02-28');
  });
  it('اسفندِ سالِ کبیسه‌ی میلادی', () => {
    expect(shiftISO('2028-02-28', 1)).toBe('2028-02-29');
  });
  it('از مرزِ سالِ میلادی درست رد می‌شود', () => {
    expect(shiftISO('2026-12-31', 1)).toBe('2027-01-01');
  });
  it('هفت روز جلوتر — همان سقفِ مجازِ رزرو', () => {
    expect(shiftISO('2026-09-20', 7)).toBe('2026-09-27');
  });
});

describe('بازه‌ی تاریخ', () => {
  it('هر دو سرِ بازه را شامل می‌شود', () => {
    expect(rangeISO('2026-09-20', '2026-09-22')).toEqual(['2026-09-20', '2026-09-21', '2026-09-22']);
  });
  it('بازه‌ی معکوس فقط روزِ شروع را برمی‌گرداند', () => {
    expect(rangeISO('2026-09-22', '2026-09-20')).toEqual(['2026-09-22']);
  });
  it('سقفِ ایمنی رعایت می‌شود', () => {
    expect(rangeISO('2026-01-01', '2026-12-31', 5)).toHaveLength(5);
  });
});

describe('ارقامِ فارسی', () => {
  it('ساعت به ارقامِ فارسی تبدیل می‌شود', () => {
    expect(toPersianDigits('09:00')).toBe('۰۹:۰۰');
  });
  it('ورودیِ فارسی و عربیِ کاربر به لاتین برمی‌گردد (برای شماره‌ی موبایل)', () => {
    expect(normalizeDigits('۰۹۱۲۳۴۵۶۷۸۹')).toBe('09123456789');
    expect(normalizeDigits('٠٩١٢')).toBe('0912');
  });
});
