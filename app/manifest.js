// مانیفستِ PWA — Next.js این فایل را به‌صورت خودکار در مسیر /manifest.webmanifest
// سرو می‌کند و لینکِ <link rel="manifest"> را در <head> تزریق می‌کند.
// داک: https://nextjs.org/docs/app/api-reference/file-conventions/metadata/manifest
//
// نامِ اپ از src/lib/shop.js می‌آید (همان منبعی که عنوانِ سایت و فوتر از آن می‌خوانند).
// قبلاً اینجا دستی نوشته شده بود؛ نتیجه‌اش این بود که با عوض‌کردنِ نامِ مجموعه، نامِ
// آیکنِ نصب‌شده روی گوشی کهنه می‌ماند — بدونِ اینکه جایی خطا بدهد.
import { SHOP_NAME } from '@/lib/shop';

export default function manifest() {
  return {
    name: SHOP_NAME,
    short_name: SHOP_NAME,
    // این متن روی گوشیِ مشتری و در فهرستِ اپ‌های نصب‌شده دیده می‌شود. قبلاً هم نامِ فارسیِ
    // «بناد» را می‌آورد (که با نامِ لاتینِ کلِ سایت یکی نبود و دو برند نشان می‌داد) و هم
    // «پنل مدیریت» را به مشتری تبلیغ می‌کرد.
    description: `رزرو آنلاین نوبت در ${SHOP_NAME}`,
    id: '/',
    start_url: '/',
    scope: '/',
    display: 'standalone',
    orientation: 'portrait',
    dir: 'rtl',
    lang: 'fa-IR',
    background_color: '#030303',
    theme_color: '#0a0a0a',
    categories: ['lifestyle', 'business'],
    // میان‌بُرها: در حالت نصب‌شده (PWA) با نگه‌داشتن (long-press) روی آیکونِ اپ ظاهر می‌شوند.
    // ⚠️ میان‌برِ «پنل مدیریت» برداشته شد: این فهرست روی گوشیِ **هر مشتری‌ای** که اپ را نصب
    // کند دیده می‌شود، و دلیلی ندارد درِ ورودِ مدیریت آنجا تبلیغ شود.
    shortcuts: [
      { name: 'رهگیری نوبت', short_name: 'رهگیری', url: '/track', description: 'پیگیری وضعیت نوبت' },
    ],
    // 🔴 آیکونِ maskable عمداً معرفی نشده است.
    // اندروید آیکونی را که maskable اعلام شود داخلِ شکلِ گوشی **برش می‌زند** و انتظار دارد
    // حدودِ ۲۰٪ حاشیه‌ی امن داشته باشد. فایلِ فعلیِ icon-maskable-512.png بایت‌به‌بایت کپیِ
    // آیکونِ معمولی است (بدونِ حاشیه)، پس معرفی‌اش باعث می‌شد لوگو از لبه‌ها بریده شود.
    // تا ساختِ نسخه‌ی حاشیه‌دار، اندروید خودش آیکونِ معمولی را در قاب جا می‌دهد — که بدترین
    // حالتش کمی فضای خالی است، نه لوگوی بریده.
    icons: [
      { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    ],
  };
}
